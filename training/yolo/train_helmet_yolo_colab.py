import os
import xml.etree.ElementTree as ET
import glob

def convert_to_yolo():
    classes = ['hat', 'person']
    # XML 파일들 찾기
    xml_files = glob.glob('/content/VOCdevkit/**/Annotations/*.xml', recursive=True)

    if not xml_files:
        print("XML 파일을 찾지 못했습니다. 경로를 확인하세요.")
        return

    # labels 폴더 생성 위치 파악
    base_dir = os.path.dirname(os.path.dirname(xml_files[0]))
    txt_path = os.path.join(base_dir, 'labels')
    os.makedirs(txt_path, exist_ok=True)

    count = 0
    for xml_file in xml_files:
        tree = ET.parse(xml_file)
        root = tree.getroot()
        size = root.find('size')
        w, h = int(size.find('width').text), int(size.find('height').text)

        with open(os.path.join(txt_path, os.path.basename(xml_file).replace('.xml', '.txt')), 'w') as f:
            for obj in root.iter('object'):
                cls = obj.find('name').text
                if cls not in classes: continue
                cls_id = classes.index(cls)
                xmlbox = obj.find('bndbox')
                b = (float(xmlbox.find('xmin').text), float(xmlbox.find('xmax').text),
                     float(xmlbox.find('ymin').text), float(xmlbox.find('ymax').text))
                # YOLO 형식 좌표 변환 (중심X, 중심Y, 너비, 높이)
                bb = ((b[0]+b[1])/2.0/w, (b[2]+b[3])/2.0/h, (b[1]-b[0])/w, (b[3]-b[2])/h)
                f.write(f"{cls_id} {' '.join([f'{a:.6f}' for a in bb])}\n")
        count += 1
    print(f"✅ 성공: {count}개의 파일을 {txt_path}에 변환 저장했습니다.")
    return base_dir

