from ultralytics import YOLO
import os

def check_helmet(image_path):
    # 1. 학습된 최적의 모델 불러오기
    # 학습이 끝났다면 runs/detect/train/weights/best.pt에 저장되어 있습니다.
    model_path = '/content/runs/detect/train/weights/best.pt'

    if not os.path.exists(model_path):
        print("모델 파일을 찾을 수 없습니다. 학습이 먼저 완료되어야 합니다.")
        return

    model = YOLO(model_path)

    # 2. 이미지 분석 (conf는 신뢰도 임계값입니다)
    results = model.predict(source=image_path, conf=0.4, save=False, verbose=False)

    # 3. 결과 분석
    helmet_detected = False
    for r in results:
        # 감지된 객체들의 클래스 ID 확인
        # 2번 셀에서 'hat'을 0번 클래스로 설정했으므로, 0이 있는지 확인합니다.
        for box in r.boxes:
            class_id = int(box.cls[0])
            if class_id == 0:  # 0: 'hat' (헬멧)
                helmet_detected = True
                break

    # 4. Y / N 출력
    if helmet_detected:
        print("Y")
    else:
        print("N")

